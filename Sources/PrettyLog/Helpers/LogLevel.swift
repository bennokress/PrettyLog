import Foundation

/// The Log Level can be used to filter log statements before they are sent to a Log Target. It also carries an emoji as a way to visually distinguish the severity of each log statement.
///
/// PrettyLog ships no Log Levels. Your app declares its own as an enum with ``LogLevels()``, one case per level, with ``Emoji(_:)`` and an `Int` raw value:
///
///     @LogLevels
///     nonisolated enum AppLogLevel: Int {
///
///         @Emoji("🟤") case debug = 100
///         @Emoji("🔴") case error = 900
///         @Emoji("🟢") case info = 500
///
///     }
///
/// The raw value is the priority. Targets compare priorities to decide what they log, and levels are ordered by priority, so the order of the cases means nothing and they can be sorted alphabetically.
/// The compiler rejects two cases with the same raw value, so every level has its own priority. The package gives a level no meaning of its own: it is up to your app what "debug" or "production" means.
///
/// A target can `switch` over the levels of your app without a `default` branch, so a new level without a mapping, for example to an `OSLogType`, does not compile.
///
/// - Attention: Always declare levels with ``LogLevels()``, never conform to `LogLevel` by hand. Swift can't restrict a protocol to enums, so the requirement `_$logLevelsMacro`, which only the macro generates, is what points a hand-written conformance to the macro.
public protocol LogLevel: RawRepresentable, CaseIterable, Comparable, Hashable, Sendable where RawValue == Int {

    /// The emoji can be used as a quickly glanceable representation of the Log Level in log statements. ``LogLevels()`` generates it from the ``Emoji(_:)`` of each case.
    var emoji: String { get }

    /// Generated by ``LogLevels()``. Don't implement it yourself: declare your levels as an enum with `@LogLevels`.
    static var _$logLevelsMacro: LogLevelsMacroMarker { get }

}

public extension LogLevel {

    /// The priority can be used to determine which log statement should be sent to a specific target; higher means more important.
    ///
    /// It is the raw value of the case. It is no requirement of the protocol, so a `priority` your enum declares itself is ignored by PrettyLog.
    var priority: Int { rawValue }

    /// Levels are ordered by priority, never by the order of their cases.
    static func < (lhs: Self, rhs: Self) -> Bool {
        lhs.priority < rhs.priority
    }

}

/// The type of the requirement `_$logLevelsMacro` of ``LogLevel``, which only ``LogLevels()`` generates.
///
/// It carries no data. It exists so that a hand-written conformance to `LogLevel` fails to compile and the compiler's message names the macro.
public struct LogLevelsMacroMarker: Sendable {

    /// Called by code that ``LogLevels()`` generates. Don't call it yourself.
    public static func _$generated() -> LogLevelsMacroMarker {
        LogLevelsMacroMarker()
    }

    private init() { }

}

/// Makes an enum with `Int` as its raw type a ``LogLevel``.
///
/// Mark every case with ``Emoji(_:)``. The macro generates `emoji`, `allCases` and the conformance to `LogLevel`, so the enum declares nothing but its cases:
///
///     @LogLevels
///     nonisolated enum AppLogLevel: Int {
///
///         @Emoji("🟤") case debug = 100
///         @Emoji("🔴") case error = 900
///
///     }
///
/// The macro reports an error if it is attached to anything but an enum with `Int` as its raw type, and for every case without `@Emoji` or with more than one level.
@attached(member, names: named(emoji), named(allCases), named(_$logLevelsMacro))
@attached(extension, conformances: LogLevel)
public macro LogLevels() = #externalMacro(module: "PrettyLogMacros", type: "LogLevelsMacro")

/// The emoji of a level in an enum with ``LogLevels()``: `@Emoji("🟤") case debug = 100`.
///
/// It generates nothing itself; `@LogLevels` reads it.
/// - Parameter emoji: The emoji shown in log statements of this level, as a string literal.
@attached(peer)
public macro Emoji(_ emoji: String) = #externalMacro(module: "PrettyLogMacros", type: "EmojiMacro")
